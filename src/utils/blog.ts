import { DateTime } from 'luxon'
import blogData from '@/data/_blog.json'
import { getSlug } from '@/tools/get-slug'
import type { PageMetadata } from '@/utils/page-helpers'

export interface BlogPost {
  slug: string
  metadata: {
    title: string
    description: string
    /** WordPress publish time (local), ISO. */
    date: string
    categories: string[]
    featuredImage: string
    author: string
    excerpt: string
    modified: string
    video?: string
  }
}

/** Posts per archive page (WordPress's "Blog pages show at most"). */
export const POSTS_PER_PAGE = 6

/** All posts, newest first (_data/_blog.json is generated by `npm run blog`). */
export function getPosts(): BlogPost[] {
  return blogData as BlogPost[]
}

export function getPostsInCategory(slug: string): BlogPost[] {
  return getPosts().filter((post) =>
    post.metadata.categories.some((name) => getSlug(name) === slug)
  )
}

/** Category names keyed by slug, from the posts that use them. */
export function getCategories(): { slug: string; name: string }[] {
  const names = new Map<string, string>()
  for (const post of getPosts())
    for (const name of post.metadata.categories) names.set(getSlug(name), name)
  return [...names].map(([slug, name]) => ({ slug, name }))
}

export function categoryHref(name: string) {
  return `/category/${getSlug(name)}/`
}

export function pageCount(posts: BlogPost[]) {
  return Math.max(1, Math.ceil(posts.length / POSTS_PER_PAGE))
}

export function pagePosts(posts: BlogPost[], page: number) {
  return posts.slice((page - 1) * POSTS_PER_PAGE, page * POSTS_PER_PAGE)
}

/** "February 19, 2021", as the theme printed post dates. */
export function formatPostDate(date: string) {
  return DateTime.fromISO(date).toFormat('LLLL d, yyyy')
}

/** Static params for the later pages of an archive (page 1 is the archive itself). */
export function laterPages(posts: BlogPost[]) {
  return Array.from({ length: pageCount(posts) - 1 }, (_, i) => ({
    page: String(i + 2),
  }))
}

/** Yoast's " - Page 2 of 3" title part (empty on page 1). */
export function pageSuffix(posts: BlogPost[], page: number) {
  return page > 1 ? ` - Page ${page} of ${pageCount(posts)}` : ''
}

/** Yoast's archive primary image: the first post shown on the page. */
export function archiveImage(
  posts: BlogPost[],
  page: number
): NonNullable<PageMetadata['primaryImage']> {
  const first = pagePosts(posts, page)[0]
  return first
    ? { url: first.metadata.featuredImage, caption: first.metadata.title }
    : false
}

export function archivePath(path: string, page: number) {
  return page > 1 ? `${path}page/${page}/` : path
}

/** The latest posts (of a category) as project cards: newest first. */
export function recentPosts(count: number, categorySlug?: string) {
  const posts = categorySlug ? getPostsInCategory(categorySlug) : getPosts()
  return posts.slice(0, count).map(({ slug, metadata }) => ({
    href: `/${slug}/`,
    title: metadata.title,
    date: formatPostDate(metadata.date),
    image: metadata.featuredImage,
    alt: metadata.title,
  }))
}
